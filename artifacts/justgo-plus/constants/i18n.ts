export function translateText(language: AppLanguage, text: string): string {
  if (language === 'en') return text;
  const exact = MS[text];
  if (exact) return exact;

  const otpNoticeSuffix = ' is not connected in this build. No request was sent and nothing was verified. Use "Explore demo" to view the app with sample data.';
  if (text.endsWith(otpNoticeSuffix)) {
    const service = text.slice(0, -otpNoticeSuffix.length);
    return `${MS[service] ?? service} belum disambungkan dalam versi ini. Tiada permintaan dihantar dan tiada apa-apa disahkan. Pilih "Teroka demo" untuk melihat aplikasi dengan data contoh.`;
  }

  const transactionPrefix = 'There are no transactions between ';
  const transactionSuffix = ', so there is nothing to download. No file was created.';
  if (text.startsWith(transactionPrefix) && text.endsWith(transactionSuffix)) {
    const range = text.slice(transactionPrefix.length, -transactionSuffix.length);
    return `Tiada transaksi antara ${range}, jadi tiada apa-apa untuk dimuat turun. Tiada fail dicipta.`;
  }

  const vehicleDeletePrefix = 'Remove ';
  const vehicleDeleteSuffix = ' from this device?';
  if (text.startsWith(vehicleDeletePrefix) && text.endsWith(vehicleDeleteSuffix)) {
    const plate = text.slice(vehicleDeletePrefix.length, -vehicleDeleteSuffix.length);
    return `Buang ${plate} daripada peranti ini?`;
  }

  return text;
}
